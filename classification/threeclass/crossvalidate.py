"""Patient-group outer CV with separate inner patients for early stopping.

Only original training data are used. Outer fold labels never select epochs or
thresholds. No external test predictions are generated by this script.
"""
import argparse
import json
import fcntl
import numpy as np
import pandas as pd
import torch
from sklearn.model_selection import StratifiedGroupKFold,train_test_split
from experiment import ROOT,load_data,train_one,Model,normalize,predict,metrics,tune_thresholds,leaf_probs,routed,dump

def main():
    p=argparse.ArgumentParser();p.add_argument('--features',default='convnext_320');p.add_argument('--seeds',type=int,default=3);p.add_argument('--candidate-json');a=p.parse_args()
    torch.set_num_threads(4)
    frame,features,digest=load_data(a.features)
    candidates=[]
    namespace='candidate_crossvalidation' if a.candidate_json else 'crossvalidation'
    if a.candidate_json:
        record=json.loads(__import__('pathlib').Path(a.candidate_json).read_text())
        assert record['feature']==a.features
        candidates=[('continuous_'+record['candidate_id'],record['config'])]
    else:
        for phase in ['baseline','explore']:
            selection=json.loads((ROOT/'runs'/a.features/phase/'selection.json').read_text())
            chosen=list(selection['selected'].values()) if phase=='baseline' else [selection['best']]
            for group in chosen: candidates.append((phase+'_'+group['group'],group['config']))
    train_indices=np.flatnonzero(frame.split.eq('train').to_numpy());train=frame.iloc[train_indices]
    splitter=StratifiedGroupKFold(n_splits=3,shuffle=True,random_state=20261125)
    folds=list(splitter.split(train,train.label,train.split_group));all_reports=[]
    comparison_path=ROOT/'runs'/a.features/namespace/'comparison.json'
    if a.candidate_json and comparison_path.exists():all_reports=json.loads(comparison_path.read_text())
    for name,cfg in candidates:
        guard=ROOT/'runs'/a.features/namespace/(name+'.run.lock')
        guard.parent.mkdir(parents=True,exist_ok=True)
        candidate_lock=guard.open('a');fcntl.flock(candidate_lock,fcntl.LOCK_EX)
        out=ROOT/'runs'/a.features/namespace/name;fold_results=[]
        for fold,(fit_local,outer_local) in enumerate(folds):
            fold_dir=out/f'fold_{fold}';report_path=fold_dir/'outer_metrics.json'
            if report_path.exists(): fold_results.append(json.loads(report_path.read_text()));continue
            fit_indices=train_indices[fit_local];outer_indices=train_indices[outer_local]
            fit=frame.iloc[fit_indices]
            patients=fit.groupby('split_group').label.agg(lambda x:x.mode().iloc[0])
            inner_ids,stop_ids=train_test_split(patients.index,test_size=.2,random_state=20261124+fold,stratify=patients)
            inner_mask=np.zeros(len(frame),dtype=bool);stop_mask=inner_mask.copy()
            inner_mask[fit_indices]=fit.split_group.isin(inner_ids);stop_mask[fit_indices]=fit.split_group.isin(stop_ids)
            assert not set(frame.loc[inner_mask,'split_group']) & set(frame.iloc[outer_indices].split_group)
            outer_ps=[];outer_gs=[];stop_ps=[];stop_gs=[]
            for seed in range(a.seeds):
                seed_dir=fold_dir/f'seed_{seed}'
                train_one(frame,features,digest,{**cfg,'seed':seed},seed_dir,inner_mask,stop_mask)
                ckpt=torch.load(seed_dir/'model.pt',map_location='cpu',weights_only=False)
                if 'memory_audit' in ckpt:
                    support=set(ckpt['memory_audit']['support_patient_groups'])
                    assert support==set(frame.loc[inner_mask,'patient_group'])
                    assert not support & set(frame.loc[stop_mask,'patient_group'])
                    assert not support & set(frame.iloc[outer_indices].patient_group)
                    assert ckpt['memory_audit']['training_query_own_patient_excluded']
                model=Model(ckpt['cfg'],ckpt['dims'],len(ckpt['diseases'])).cuda();model.load_state_dict(ckpt['state_dict'],strict=True)
                normalized,_=normalize({k:v[outer_indices] for k,v in features.items()},None,ckpt['stats'])
                x={k:torch.from_numpy(v).cuda() for k,v in normalized.items()}
                pp,gg=predict(model,x);outer_ps.append(pp);outer_gs.append(gg)
                v=np.load(seed_dir/'val_predictions.npz');stop_ps.append(v['p']);stop_gs.append(v['g'])
                del model,x;torch.cuda.empty_cache()
            g=np.mean(outer_gs,0);pp=leaf_probs(g,cfg['mode']) if g.shape[1] else np.mean(outer_ps,0)
            if g.shape[1]:
                thresholds=tune_thresholds(frame.loc[stop_mask,'label'],np.mean(stop_gs,0),cfg['mode'])
                pred=routed(g,cfg['mode'],thresholds)
            else: thresholds=None;pred=pp.argmax(1)
            result={'fold':fold,'inner_train_images':int(inner_mask.sum()),'early_stop_images':int(stop_mask.sum()),'outer_test_images':len(outer_indices),'thresholds_from_inner_stop_only':thresholds,'metrics':metrics(frame.iloc[outer_indices].label,pp,pred)}
            if cfg['arch'] in ['memory_hybrid','memory_attention']:result['memory_support_audit_passed']=True
            dump(report_path,result);np.savez_compressed(fold_dir/'outer_predictions.npz',indices=outer_indices,p=pp,g=g,pred=pred)
            fold_results.append(result)
            print(json.dumps({'candidate':name,'fold':result}),flush=True)
        summary={'candidate':name,'config':cfg,'folds':fold_results,'mean_macro_f1':float(np.mean([f['metrics']['macro_f1'] for f in fold_results])),'sd_macro_f1':float(np.std([f['metrics']['macro_f1'] for f in fold_results],ddof=1)),'mean_accuracy':float(np.mean([f['metrics']['accuracy'] for f in fold_results])),'policy':'3 outer patient-group folds using original training data only; disjoint inner early-stopping patients; thresholds selected only on inner stop patients; 3 seeds per fold.'}
        dump(out/'summary.json',summary)
        with comparison_path.with_suffix('.lock').open('a') as lock:
            fcntl.flock(lock,fcntl.LOCK_EX)
            all_reports=[json.loads(path.read_text()) for path in comparison_path.parent.glob('*/summary.json')]
            dump(comparison_path,sorted(all_reports,key=lambda x:x['mean_macro_f1'],reverse=True))
        candidate_lock.close()

if __name__=='__main__': main()
